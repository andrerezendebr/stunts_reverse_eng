//! First arithmetic routine ported from the reconstructed game image.

/// Signed fixed-point multiplication with 14 fractional bits (1.0 = 0x4000).
/// Mirrors multiply_and_scale at Ghidra 2EA2:1624: IMUL, two SHL/RCL pairs,
/// then SHL/ADC to round using the highest discarded bit. Ties round toward
/// positive infinity; the returned word wraps rather than saturates.
pub fn multiply_and_scale(a: i16, b: i16) -> i16 {
    let product = i32::from(a) * i32::from(b);
    // A full-range product shifted twice may overflow i32. The DOS registers
    // discard those bits, so use explicit wrapping instead of Rust's debug panic.
    let shifted = product.wrapping_shl(2);
    let high = shifted >> 16;
    let rounding_bit = ((shifted as u32 >> 15) & 1) as i32;
    high.wrapping_add(rounding_bit) as i16
}

#[cfg(test)]
mod tests {
    use super::multiply_and_scale;

    #[test]
    fn matches_original_dos_instructions_executed_in_unicorn() {
        // Generated by tools/verify_fixed_mul.py from the exact DOS machine code.
        // Unlike a formula-only check, these expected values come from execution.
        let fixture = include_str!("../tests/fixtures/fixed-mul-dos.csv");
        let mut count = 0;
        for line in fixture.lines().skip(1) {
            let values: Vec<i16> = line.split(',').map(|s| s.parse().unwrap()).collect();
            assert_eq!(
                multiply_and_scale(values[0], values[1]),
                values[2],
                "{line}"
            );
            count += 1;
        }
        assert_eq!(count, 249);
    }

    #[test]
    fn signed_ties_and_wrapping_match_the_instruction_contract() {
        assert_eq!(multiply_and_scale(0x4000, 1234), 1234);
        assert_eq!(multiply_and_scale(1, 8192), 1);
        assert_eq!(multiply_and_scale(-1, 8192), 0);
        assert_eq!(multiply_and_scale(i16::MIN, i16::MIN), 0);
        // Independent wide-integer expression avoids emulating the same shifts.
        for a in i16::MIN..=i16::MAX {
            for b in [
                i16::MIN,
                -32767,
                -16384,
                -8192,
                -1,
                0,
                1,
                8192,
                16384,
                32767,
            ] {
                let expected = ((i64::from(a) * i64::from(b) + 8192) >> 14) as i16;
                assert_eq!(multiply_and_scale(a, b), expected, "a={a}, b={b}");
            }
        }
    }
}
